// shadcn `card` (new-york), copied in by hand and themed to the noir tokens
// (Spec 09 D1). Card = the raised `ink-2` surface with the one shared radius
// (rounded-lg), border (smoke/60), and the single card-lift shadow
// (`shadow-card`, from index.css's `--shadow-card`). CardHeader/Content/Footer
// give the one padding + vertical-rhythm vocabulary every screen composes
// instead of hand-rolling per-screen padding.
